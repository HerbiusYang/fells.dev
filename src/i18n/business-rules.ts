export function businessRulesOf(language: string) {
  const code = language.toLowerCase();
  if (code.startsWith("zh-hant") || code.startsWith("zh-tw")) return businessRules["zh-hant"];
  if (code.startsWith("zh")) return businessRules.zh;
  if (code.startsWith("ja")) return businessRules.ja;
  if (code.startsWith("ko")) return businessRules.ko;
  if (code.startsWith("es")) return businessRules.es;
  return businessRules.en;
}
